//! `drm info --license --cpix <path>` real-behaviour tests (SLICE 4F).
//!
//! `--license` previously always warned "not implemented" and produced no
//! license output at all. It now reads a real CPIX (Content Protection
//! Information Exchange) sidecar document via
//! `oximedia_drm::cpix::CpixDocument::from_xml` and surfaces the genuine
//! license URL / DRM system / key ID data it contains.

use assert_cmd::Command;

/// A CPIX document using exactly the element/attribute names
/// `oximedia_drm::cpix::CpixDocument::{to_xml,from_xml}` round-trip on
/// (`from_xml` is documented as "a lightweight pull-parser that handles the
/// subset of CPIX XML generated by `to_xml()`" — notably `URIExtXKey` for
/// the license URL, not any real-world CPIX/DASH-IF element name — so this
/// fixture matches the crate's own format rather than the public CPIX spec).
const CPIX_FIXTURE: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<CPIX xmlns="urn:dashif:org:cpix" contentId="movie-001" version="2.3">
  <ContentKeyList>
    <ContentKey kid="key-alpha"/>
  </ContentKeyList>
  <DRMSystemList>
    <DRMSystem systemId="edef8ba9-79d6-4ace-a3c8-27dcd51d21ed" kid="key-alpha">
      <PSSH>AAAAIHBzc2gAAAAA7t</PSSH>
      <URIExtXKey>https://license.example.com/widevine</URIExtXKey>
    </DRMSystem>
  </DRMSystemList>
</CPIX>
"#;

fn write_cpix_fixture(dir: &std::path::Path) -> std::path::PathBuf {
    let path = dir.join("fixture.cpix.xml");
    std::fs::write(&path, CPIX_FIXTURE).expect("write cpix fixture");
    path
}

#[test]
fn license_with_cpix_reports_real_license_url_in_json() {
    let dir = tempfile::TempDir::new().expect("tempdir");
    let media = dir.path().join("media.bin");
    std::fs::write(&media, b"placeholder protected media bytes").expect("write media");
    let cpix = write_cpix_fixture(dir.path());

    let assert = Command::cargo_bin("oximedia")
        .expect("binary builds")
        .args([
            "drm",
            "info",
            "--input",
            media.to_str().expect("utf8"),
            "--license",
            "--cpix",
            cpix.to_str().expect("utf8"),
            "--json",
        ])
        .assert()
        .success();

    let stdout = String::from_utf8_lossy(&assert.get_output().stdout).to_string();
    let value: serde_json::Value = serde_json::from_str(stdout.trim()).expect("valid JSON");
    assert_eq!(
        value["license"]["content_id"], "movie-001",
        "got:\n{stdout}"
    );
    assert_eq!(
        value["license"]["drm_systems"][0]["license_url"], "https://license.example.com/widevine",
        "the real license URL from the CPIX document must be surfaced, got:\n{stdout}"
    );
    assert_eq!(
        value["license"]["drm_systems"][0]["system_id"], "edef8ba9-79d6-4ace-a3c8-27dcd51d21ed",
        "got:\n{stdout}"
    );
}

/// Without `--cpix`, `--license` must not silently produce nothing: it
/// states plainly (stderr) that no embedded-license reader exists for raw
/// media files, and the JSON `license` field must be present (not
/// omitted/fabricated).
#[test]
fn license_without_cpix_is_honest_not_silent() {
    let dir = tempfile::TempDir::new().expect("tempdir");
    let media = dir.path().join("media.bin");
    std::fs::write(&media, b"placeholder bytes").expect("write media");

    let assert = Command::cargo_bin("oximedia")
        .expect("binary builds")
        .args([
            "drm",
            "info",
            "--input",
            media.to_str().expect("utf8"),
            "--license",
            "--json",
        ])
        .assert()
        .success();

    let stdout = String::from_utf8_lossy(&assert.get_output().stdout).to_string();
    let value: serde_json::Value = serde_json::from_str(stdout.trim()).expect("valid JSON");
    assert!(
        value.get("license").is_some(),
        "the license key must be present (even if null) rather than silently omitted"
    );

    let stderr = String::from_utf8_lossy(&assert.get_output().stderr).to_string();
    assert!(
        stderr.contains("--cpix"),
        "must point the user at --cpix as the real route, got:\n{stderr}"
    );
}

/// A malformed `--cpix` document must fail loudly, not be silently ignored.
#[test]
fn malformed_cpix_document_is_a_real_error() {
    let dir = tempfile::TempDir::new().expect("tempdir");
    let media = dir.path().join("media.bin");
    std::fs::write(&media, b"placeholder bytes").expect("write media");
    let cpix = dir.path().join("bad.xml");
    std::fs::write(&cpix, b"not xml at all <<<").expect("write garbage");

    Command::cargo_bin("oximedia")
        .expect("binary builds")
        .args([
            "drm",
            "info",
            "--input",
            media.to_str().expect("utf8"),
            "--license",
            "--cpix",
            cpix.to_str().expect("utf8"),
        ])
        .assert()
        .failure();
}
